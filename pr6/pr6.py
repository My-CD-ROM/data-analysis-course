print(f"3. Генеральна дисперсія (ddof=0):             {var_pop:.4f}")
print(
    f"   -> Різниця (ddof=1 проти ddof=0):          {var_sample - var_pop:.4f}"
)
print(f"4. Стандартне відхилення (std):              {std_val:.4f}%")
print(f"5. Перший квартиль (Q1 / 25%):                {q1:.2f}%")
print(f"6. Третій квартиль (Q3 / 75%):                {q3:.2f}%")
print(f"7. Міжквартильний розмах (IQR = Q3 - Q1):     {iqr:.2f}%")
print(f"8. Коефіцієнт варіації (CV):                  {cv_kyiv:.2f}%")

