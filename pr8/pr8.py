import numpy as np
import pandas as pd

np.random.seed(42)
base_temp = 9.5
amplitude = 14.0
city = "Київ"

rows = []
for year in [2021, 2022, 2023, 2024]:
    for month in range(1, 13):
        seasonal = amplitude * np.cos((month - 7) / 12 * 2 * np.pi)
        noise = np.random.normal(0, 1.0)
        rows.append({
            "місто": city,
            "рік": year,
            "місяць": month,
            "температура": round(base_temp + seasonal + noise, 1),
        })

climate = pd.DataFrame(rows)

print("=" * 60)
print("ПРАКТИЧНА РОБОТА 8 (Варіант 1: Київ)")
print("=" * 60)

print("\n--- Вихідні дані (перші 5 рядків) ---")
print(climate.head())

print("\n--- Завдання 1. groupby і agg за роками ---")
task1_res = climate.groupby("рік")["температура"].agg(["mean", "min", "max"])
print(task1_res)
print("\nПисьмовий висновок до Завдання 1:")
print("Вираженого тренду потепління чи похолодання не спостерігається. Середньорічні значення коливаються у межах ~8.9°C–9.8°C навколо базової температури 9.5°C, а мінімуми й максимуми змінюються без чіткої динаміки, що вказує на випадковий характер коливань (зумовлений випадковим шумом у даних).")

print("\n--- Завдання 2. groupby і agg за місяцями ---")
task2_res = climate.groupby("місяць")["температура"].agg(["mean", "std"])
print(task2_res)
max_std_month = task2_res["std"].idxmax()
print(f"\nНайбільший розкид (std = {task2_res.loc[max_std_month, 'std']:.2f}) спостерігається у місяці №{max_std_month}.")
print("Письмовий висновок до Завдання 2:")
print("У даному синтетичному наборі найбільший розкид виявився у серпні (місяць 8) через випадкові стохастичні відхилення. У реальних кліматичних умовах найнестабільнішими зазвичай є саме перехідні місяці (березень, квітень, жовтень, листопад), оскільки в ці періоди відбуваються активна перебудова атмосферних циркуляцій і різка зміна повітряних мас.")

print("\n--- Завдання 3. pivot_table ---")
task3_res = climate.pivot_table(index="місяць", columns="рік", values="температура", aggfunc="mean")
print(task3_res)
print("\nПисьмовий висновок до Завдання 3:")
print("1. Зручність для читання людиною: Зведена форма (pivot_table) значно зручніша для швидкого сприйняття, оскільки дозволяє легко порівнювати однакові місяці різних років в одному рядку.")
print("2. Зручність для групування та графіків: Довгий (tidy) формат кращий для подальшого аналізу й побудови графіків (наприклад, у Seaborn/Plotly), адже всі виміри (рік, місяць) винесені в окремі стовпці-фактори.")

print("\n--- Завдання 4. Похідні категорії і crosstab ---")
def get_season(m):
    if m in [12, 1, 2]:
        return "зима"
    elif m in [3, 4, 5]:
        return "весна"
    elif m in [6, 7, 8]:
        return "літо"
    else:
        return "осінь"

climate["сезон"] = climate["місяць"].apply(get_season)
climate["тепліше_за_середнє"] = climate["температура"] > base_temp
task4_res = pd.crosstab(climate["сезон"], climate["тепліше_за_середнє"])
print(task4_res)
print("\nПисьмовий висновок до Завдання 4:")
print("Розподіл повністю узгоджується з очікуваннями: усі 12 літніх місяців за 4 роки потрапили до категорії 'тепліше за середнє' (True = 12, False = 0), а всі 12 зимових місяців — до категорії нижче середнього (False = 12, True = 0). У весняні та осінні місяці спостерігається природний поділ залежно від того, наскільки конкретний місяць близький до літа чи зими.")

print("\n--- Завдання 5. pivot() на своєму наборі ---")
task5_res = climate.pivot(index="місяць", columns="рік", values="температура")
print(task5_res)
print("\nПисьмовий висновок до Завдання 5:")
print("1. Чому pivot() спрацював: На відміну від прикладу з кав'ярнями, у нашому наборі climate на кожну комбінацію (місяць, рік) припадає лише 1 рядок (1 спостереження). Оскільки дублікатів немає, pivot() спроможний однозначно розмістити кожне значення без агрегації.")
print("2. Яка зміна викликала б помилку: Якби до структури даних додали ще один вимір — наприклад, вимірювання з кількох метеостанцій міста ('станція_1', 'станція_2'), то для кожної комбінації (місяць, рік) існувало б по кілька рядків. У цьому випадку pivot() видав би ValueError, і для зведення знадобився б pivot_table() із вказаним aggfunc.")

print("\n" + "=" * 60)
print("ВІДПОВІДІ НА КОНТРОЛЬНІ ПИТАННЯ")
print("=" * 60)
print("1. Логіка split-apply-combine у groupby():")
print("   - Split (розбиття): вхідний DataFrame розділяється на окремі групи за значеннями вибраного ключа (наприклад, за роками чи місяцями).")
print("   - Apply (застосування): до кожної утвореної групи незалежно застосовується якась функція (наприклад, обчислення mean, std, min, max).")
print("   - Combine (об'єднання): результати обчислень з усіх груп збираються назад у єдину підсумкову структуру (Series або DataFrame).")

print("\n2. Відмінність між pivot() та pivot_table():")
print("   - pivot() відповідає виключно за зміну форми (reshaping) без агрегації. Якщо для комбінації (index, columns) є більше одного значення, виникає ValueError.")
print("   - pivot_table() підтримує агрегацію через параметр aggfunc. Якщо є декілька рядків на одну клітинку, він автоматично зводить їх у єдине число (наприклад, шукає суму або середнє).")

print("\n3. Що показує crosstab() та відмінність від groupby(...).size():")
print("   - crosstab() обчислює таблицю частот (сопряженности) для двох або більше категоріальних змінних у вигляді зручної двовимірної матриці.")
print("   - groupby(...).size() рахує кількість спостережень для комбінацій категорій, але повертає результат у вигляді 1D Series із мультиіндексом. Для отримання вигляду матриці після groupby потрібно додатково викликати .unstack().")

print("\n4. Чому дані мають бути в довгому (tidy) форматі:")
print("   - У tidy-форматі кожен рядок є окремим спостереженням, а кожен стовпець — окремою змінною.")
print("   - Методи groupby та pivot_table побудовані навколо такої структури, оскільки це дозволяє довільно обирати стовпці для групування, фільтрації й агрегації без зміни архітектури всієї таблиці.")