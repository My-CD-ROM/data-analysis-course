import numpy as np
import pandas as pd

# Базові параметри для Варіанта 1 (Київ)
BASE_PRICE = 850
BASE_QTY = 3

# Завдання 1. Побудова набору клієнтів (10 замовлень)
data = {
    "вік": [22, 45, 29, 58, 35, 62, 19, 41, 50, 27],
    "дохід": [18000, 45000, 28000, 52000, 35000, 60000, 15000, 40000, 48000, 24000],
    "кількість": [2, 4, 3, 1, 5, 2, 3, 4, 2, 3],
    "місто_доставки": ["Київ", "Львів", "Одеса", "Харків", "Київ", "Львів", "Одеса", "Київ", "Харків", "Дніпро"]
}

df = pd.DataFrame(data)

# Завдання 2. Похідна змінна
df["сума_замовлення"] = BASE_PRICE * df["кількість"]
df["частка_доходу"] = df["сума_замовлення"] / df["дохід"]

# Завдання 3. Дискретизація
df["вік_cut"] = pd.cut(df["вік"], bins=3)
df["вік_qcut"] = pd.qcut(df["вік"], q=3)

print("Розподіл pd.cut():\n", df["вік_cut"].value_counts())
print("\nРозподіл pd.qcut():\n", df["вік_qcut"].value_counts())

# Завдання 4. Масштабування
# Min-Max нормалізація [0, 1]
df["вік_minmax"] = (df["вік"] - df["вік"].min()) / (df["вік"].max() - df["вік"].min())
df["дохід_minmax"] = (df["дохід"] - df["дохід"].min()) / (df["дохід"].max() - df["дохід"].min())

# Z-оцінка (Стандартизація)
df["вік_z"] = (df["вік"] - df["вік"].mean()) / df["вік"].std()
df["дохід_z"] = (df["дохід"] - df["дохід"].mean()) / df["дохід"].std()

print("\nПорівняння масштабованих ознак (перші 5 рядків):")
print(df[["вік", "вік_minmax", "вік_z", "дохід", "дохід_minmax", "дохід_z"]].head())

# Завдання 5. Індикаторне кодування
city_dummies = pd.get_dummies(df["місто_доставки"], prefix="місто", dtype=int)
df = pd.concat([df, city_dummies], axis=1)

print("\nКількість унікальних міст:", df["місто_доставки"].nunique())
print("Кількість створених індикаторних стовпців:", city_dummies.shape[1])
print("\nПідсумкова таблица (перші 5 рядків):")
print(df.head())