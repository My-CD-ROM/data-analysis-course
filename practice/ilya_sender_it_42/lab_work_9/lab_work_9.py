import pandas as pd

# Варіант 9
city = "Суми"
base_price = 730
base_quantity = 2

# Завдання 1. Побудова набору клієнтів

data = pd.DataFrame([
    {"вік": 21, "дохід": 18000, "кількість": 2, "місто_доставки": "Суми"},
    {"вік": 27, "дохід": 24000, "кількість": 3, "місто_доставки": "Полтава"},
    {"вік": 34, "дохід": 32000, "кількість": 2, "місто_доставки": "Київ"},
    {"вік": 41, "дохід": 41000, "кількість": 4, "місто_доставки": "Харків"},
    {"вік": 49, "дохід": 52000, "кількість": 3, "місто_доставки": "Суми"},
    {"вік": 56, "дохід": 46000, "кількість": 2, "місто_доставки": "Львів"},
    {"вік": 63, "дохід": 68000, "кількість": 5, "місто_доставки": "Одеса"},
    {"вік": 30, "дохід": 29000, "кількість": 1, "місто_доставки": "Полтава"},
    {"вік": 38, "дохід": 37000, "кількість": 3, "місто_доставки": "Харків"},
    {"вік": 68, "дохід": 75000, "кількість": 4, "місто_доставки": "Київ"}
])

print("Варіант 9")
print("Місто:", city)
print("Базова ціна:", base_price, "грн")
print("Базова кількість:", base_quantity)

print("\nЗавдання 1. Побудова набору клієнтів")
print(data)


# Завдання 2. Похідна змінна

data["сума_замовлення"] = base_price * data["кількість"]
data["частка_доходу"] = data["сума_замовлення"] / data["дохід"]

print("\nЗавдання 2. Похідна змінна")
print(data[[
    "вік",
    "дохід",
    "кількість",
    "сума_замовлення",
    "частка_доходу"
]])

print("\nВисновок:")
print("Частка доходу показує, яку частину місячного доходу клієнт витратив")
print("на замовлення. Вона враховує не тільки суму покупки, а й рівень доходу.")
print("Тому ця змінна дає змогу краще порівнювати клієнтів із різним доходом.")


# Завдання 3. Дискретизація

data["вікова_група_cut"] = pd.cut(
    data["вік"],
    bins=3
)

data["вікова_група_qcut"] = pd.qcut(
    data["вік"],
    q=3
)

print("\nЗавдання 3. Дискретизація")

print("\nГрупи віку через pd.cut():")
print(data["вікова_група_cut"])

print("\nКількість клієнтів у кожній групі cut:")
print(data["вікова_група_cut"].value_counts().sort_index())

print("\nГрупи віку через pd.qcut():")
print(data["вікова_група_qcut"])

print("\nКількість клієнтів у кожній групі qcut:")
print(data["вікова_група_qcut"].value_counts().sort_index())

print("\nВисновок:")
print("pd.cut() створює інтервали однакової довжини за значеннями змінної.")
print("Тому кількість клієнтів у групах може бути різною.")
print("pd.qcut() формує групи приблизно з однаковою кількістю спостережень.")
print("Тому межі інтервалів у qcut можуть мати різну довжину.")


# Завдання 4. Масштабування

# Min-max нормалізація
data["вік_minmax"] = (
    (data["вік"] - data["вік"].min()) /
    (data["вік"].max() - data["вік"].min())
)

data["дохід_minmax"] = (
    (data["дохід"] - data["дохід"].min()) /
    (data["дохід"].max() - data["дохід"].min())
)

# Z-оцінка
data["вік_z"] = (
    (data["вік"] - data["вік"].mean()) /
    data["вік"].std()
)

data["дохід_z"] = (
    (data["дохід"] - data["дохід"].mean()) /
    data["дохід"].std()
)

print("\nЗавдання 4. Масштабування")

print("\nMin-max нормалізація:")
print(data[[
    "вік",
    "дохід",
    "вік_minmax",
    "дохід_minmax"
]].head())

print("\nZ-оцінка:")
print(data[[
    "вік",
    "дохід",
    "вік_z",
    "дохід_z"
]].head())

print("\nВисновок:")
print("Вік вимірюється десятками років, а дохід — десятками тисяч гривень.")
print("Тому до масштабування ці змінні мають дуже різний масштаб.")
print("Min-max приводить значення до діапазону від 0 до 1.")
print("Z-оцінка показує, наскільки значення відхиляється від середнього")
print("у одиницях стандартного відхилення.")
print("Масштабування потрібне для методів, чутливих до масштабу змінних.")


# Завдання 5. Індикаторне кодування

city_dummies = pd.get_dummies(
    data["місто_доставки"],
    prefix="місто"
)

data = pd.concat([data, city_dummies], axis=1)

print("\nЗавдання 5. Індикаторне кодування")

print("\nУнікальні міста:")
print(data["місто_доставки"].unique())

print("\nOne-hot кодування:")
print(city_dummies)

print("\nКількість унікальних міст:",
      data["місто_доставки"].nunique())

print("Кількість нових стовпців:",
      city_dummies.shape[1])

print("\nПеревірка:")
print(
    "Кількість стовпців дорівнює кількості унікальних міст:",
    city_dummies.shape[1] == data["місто_доставки"].nunique()
)

print("\nПідсумковий DataFrame:")
print(data)

print("\nВисновок:")
print("Місто є номінальною змінною, тобто міста не мають природного порядку.")
print("One-hot кодування створює окремий індикатор для кожного міста.")
print("Числове кодування 1, 2, 3 тощо було б некоректним,")
print("оскільки воно створило б штучний порядок між містами.")


# Контрольні питання

print("\nКонтрольні питання")

print("\n1. Різниця між pd.cut() і pd.qcut():")
print("pd.cut() ділить діапазон значень на інтервали однакової довжини.")
print("pd.qcut() ділить дані так, щоб у групах була приблизно однакова")
print("кількість спостережень.")

print("\n2. Чому для міста використовують one-hot:")
print("Місто є номінальною категорією без природного порядку.")
print("One-hot не створює хибного числового співвідношення між містами.")

print("\n3. Навіщо масштабувати змінні:")
print("Масштабування усуває вплив різних одиниць вимірювання та порядків")
print("величин. Це особливо важливо для методів, які використовують")
print("відстані або чутливі до величини коефіцієнтів.")

print("\n4. Навіщо потрібна похідна змінна:")
print("Похідна змінна може поєднувати кілька початкових показників")
print("і давати більш змістовну характеристику.")
print("Наприклад, частка доходу показує відносне фінансове навантаження")
print("замовлення на клієнта.")
