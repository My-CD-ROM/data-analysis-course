import numpy as np
from scipy import stats

# Варіант 9 — Суми, липень = 20 °C

# Завдання 1
np.random.seed(9)
daily_temps = np.random.normal(loc=20, scale=2.5, size=30)

print("Вибірка:")
print(daily_temps)
print("\nСереднє:", daily_temps.mean())
print("Стандартне відхилення:", daily_temps.std(ddof=1))


# Завдання 2
mean = daily_temps.mean()
s = daily_temps.std(ddof=1)
n = len(daily_temps)

se = s / np.sqrt(n)

ci_mean = stats.t.interval(
    0.95,
    df=n - 1,
    loc=mean,
    scale=se
)

print("\nЗавдання 2")
print("SE =", se)
print("95% ДІ для середньої:", ci_mean)

print("""
Письмова відповідь:
Z-критичне значення не використовуємо, тому що справжнє стандартне
відхилення σ невідоме. Ми маємо лише вибіркове стандартне відхилення s,
а обсяг вибірки невеликий (n = 30), тому потрібно використовувати
t-розподіл Стьюдента.
""")


# Завдання 3
p_hat = (daily_temps > 20).mean()
n_p = n * p_hat
n_1p = n * (1 - p_hat)

se_p = np.sqrt(p_hat * (1 - p_hat) / n)

ci_prop = stats.norm.interval(
    0.95,
    loc=p_hat,
    scale=se_p
)

print("\nЗавдання 3")
print("p_hat =", p_hat)
print("n * p_hat =", n_p)
print("n * (1 - p_hat) =", n_1p)
print("95% ДІ для частки:", ci_prop)

print("""
Письмова відповідь:
n*p_hat = 16, а n*(1-p_hat) = 14. Обидва значення більші за 5,
тому умова застосування нормального наближення виконується.

Теоретично частка днів із температурою вище 20 °C близька до 0.5.
Значення 0.5 потрапляє в отриманий 95% довірчий інтервал.
""")


# Завдання 4
ci_90 = stats.t.interval(0.90, df=n-1, loc=mean, scale=se)
ci_95 = stats.t.interval(0.95, df=n-1, loc=mean, scale=se)
ci_99 = stats.t.interval(0.99, df=n-1, loc=mean, scale=se)

width_90 = ci_90[1] - ci_90[0]
width_95 = ci_95[1] - ci_95[0]
width_99 = ci_99[1] - ci_99[0]

print("\nЗавдання 4")
print("90%:", ci_90, "ширина =", width_90)
print("95%:", ci_95, "ширина =", width_95)
print("99%:", ci_99, "ширина =", width_99)

print("""
Письмова відповідь:
Ширина інтервалу зростає: 90% < 95% < 99%.
Чим вищий рівень довіри, тим більший критичний коефіцієнт і тим ширший
інтервал. Щоб отримати вужчий 99% інтервал за того самого рівня довіри,
потрібно збільшити обсяг вибірки n.
""")


