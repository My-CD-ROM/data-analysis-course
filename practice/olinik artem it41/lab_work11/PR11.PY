import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# ПРАКТИЧНА РОБОТА №11
# Числові характеристики випадкової величини;
# закон великих чисел і ЦГТ симуляцією
# ============================================================

# Варіант 1 — Київ
VARIANT = 1
CITY = "Київ"
LAMBDA = 0.20

# Теоретичне середнє експоненційного розподілу
TRUE_MEAN = 1 / LAMBDA

# Генератор випадкових чисел
rng = np.random.default_rng(VARIANT)

print("=" * 65)
print("ПРАКТИЧНА РОБОТА №11")
print("Закон великих чисел і центральна гранична теорема")
print("=" * 65)

print(f"\nВаріант: {VARIANT}")
print(f"Місто: {CITY}")
print(f"λ = {LAMBDA} подій/хв")
print(f"Теоретичне E[X] = 1/λ = {TRUE_MEAN:.2f} хв")


# ============================================================
# ЗАВДАННЯ 1
# Перевірка закону великих чисел
# ============================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 1. Перевірка закону великих чисел")
print("=" * 65)

sample_sizes = [5, 50, 500, 20_000]

print("\n{:>10} {:>20} {:>25}".format(
    "n", "Середнє", "Абсолютна різниця"
))
print("-" * 60)

for n in sample_sizes:
    sample = rng.exponential(
        scale=1 / LAMBDA,
        size=n
    )

    sample_mean = sample.mean()
    difference = abs(sample_mean - TRUE_MEAN)

    print("{:>10} {:>20.4f} {:>25.4f}".format(
        n,
        sample_mean,
        difference
    ))

print("""
Висновок:
зі збільшенням розміру вибірки n вибіркове середнє
загалом наближається до теоретичного середнього E[X].
Це демонструє закон великих чисел.
Невеликі коливання можливі через випадковість симуляції.
""")


# ============================================================
# ЗАВДАННЯ 2
# Вибірковий розподіл середнього для n=10 та n=300
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 2. Вибірковий розподіл середнього")
print("=" * 65)

n_repeats = 10_000

# n = 10
samples_n10 = rng.exponential(
    scale=1 / LAMBDA,
    size=(n_repeats, 10)
)

means_n10 = samples_n10.mean(axis=1)

# n = 300
samples_n300 = rng.exponential(
    scale=1 / LAMBDA,
    size=(n_repeats, 300)
)

means_n300 = samples_n300.mean(axis=1)

print(f"\nКількість повторних вибірок: {n_repeats}")

print(f"\nn = 10:")
print(f"Середнє x̄: {means_n10.mean():.4f}")
print(f"Стандартне відхилення: {means_n10.std():.4f}")

print(f"\nn = 300:")
print(f"Середнє x̄: {means_n300.mean():.4f}")
print(f"Стандартне відхилення: {means_n300.std():.4f}")

# Графіки
fig, axes = plt.subplots(1, 2, figsize=(12, 5))

axes[0].hist(
    means_n10,
    bins=40,
    density=True,
    edgecolor="black",
    alpha=0.7
)
axes[0].set_title("Вибірковий розподіл x̄, n = 10")
axes[0].set_xlabel("Вибіркове середнє")
axes[0].set_ylabel("Густина")

axes[1].hist(
    means_n300,
    bins=40,
    density=True,
    edgecolor="black",
    alpha=0.7
)
axes[1].set_title("Вибірковий розподіл x̄, n = 300")
axes[1].set_xlabel("Вибіркове середнє")
axes[1].set_ylabel("Густина")

plt.tight_layout()
plt.show()

print("""
Висновок:
при n = 10 розподіл вибіркового середнього ще має
помітну праву асиметрію через експоненційний характер
початкових даних.

При n = 300 розподіл x̄ стає значно більш симетричним
і наближається до дзвоноподібної нормальної форми.
Це демонструє центральну граничну теорему.
""")


# ============================================================
# ЗАВДАННЯ 3
# Стандартна похибка: теорія проти симуляції
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 3. Стандартна похибка")
print("=" * 65)

n_values = [10, 30, 100, 300]

print("\n{:>10} {:>20} {:>25}".format(
    "n",
    "Теоретична SE",
    "Виміряна std"
))
print("-" * 60)

for n in n_values:

    # Теоретична стандартна похибка
    se_theoretical = TRUE_MEAN / np.sqrt(n)

    # 10 000 повторних вибірок
    samples = rng.exponential(
        scale=1 / LAMBDA,
        size=(n_repeats, n)
    )

    sample_means = samples.mean(axis=1)

    # Стандартне відхилення вибіркових середніх
    measured_std = sample_means.std()

    print("{:>10} {:>20.4f} {:>25.4f}".format(
        n,
        se_theoretical,
        measured_std
    ))

print("""
Висновок:
теоретична стандартна похибка та виміряне стандартне
відхилення вибіркових середніх мають близькі значення.

Невелика різниця виникає через випадковість симуляції.
Зі збільшенням кількості повторних вибірок оцінка
стає стабільнішою.
""")


# ============================================================
# ЗАВДАННЯ 4
# Закон убуваючої віддачі
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 4. Закон убуваючої віддачі")
print("=" * 65)

n25 = 25
n100 = 100

se25 = TRUE_MEAN / np.sqrt(n25)
se100 = TRUE_MEAN / np.sqrt(n100)

print(f"\nSE для n = 25:  {se25:.4f}")
print(f"SE для n = 100: {se100:.4f}")

print(f"\nВідношення SE(25) / SE(100): {se25 / se100:.2f}")

print("""
Висновок:
при збільшенні n з 25 до 100 розмір вибірки збільшується
у 4 рази, але стандартна похибка зменшується лише у 2 рази.

Причина полягає у формулі:

SE = σ / √n

Оскільки n збільшилось у 4 рази, √n збільшилось
у 2 рази. Тому для зменшення стандартної похибки
вдвічі потрібно збільшити розмір вибірки у 4 рази.
""")


