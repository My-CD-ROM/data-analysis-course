print("=" * 65)

print("""
1. Різниця між точковою оцінкою і довірчим інтервалом:

Точкова оцінка дає одне число, наприклад вибіркове
середнє x̄. Вона не показує, наскільки це число
може відрізнятися від справжнього параметра.

Довірчий інтервал дає діапазон можливих значень
параметра та показує невизначеність оцінки.


2. Чому використовують t-розподіл?

Коли справжнє σ невідоме, ми оцінюємо його за допомогою
вибіркового стандартного відхилення s.

Для невеликої вибірки це створює додаткову невизначеність,
яку враховує t-розподіл. Тому для n = 30 і невідомого σ
використовують t-розподіл, а не стандартний нормальний
розподіл.


3. Що означає 95% довіри?

95% довіри означає властивість процедури побудови
інтервалу: якщо багато разів брати вибірки одного типу
і будувати інтервали тим самим методом, приблизно
95% цих інтервалів міститимуть справжній параметр.

Не можна правильно говорити:
"ймовірність того, що справжнє значення знаходиться
вже в цьому конкретному інтервалі, дорівнює 95%".


4. Які фактори визначають ширину довірчого інтервалу?

Основні фактори:

1) Рівень довіри — чим він вищий, тим ширший інтервал.

2) Варіативність даних — чим більше стандартне
   відхилення, тим ширший інтервал.

3) Розмір вибірки — чим більша вибірка, тим менша
   стандартна похибка і тим вужчий інтервал.
""")


