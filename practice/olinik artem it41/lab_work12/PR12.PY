import numpy as np
from scipy import stats

# ============================================================
# ПРАКТИЧНА РОБОТА №12
# Довірчі інтервали для середнього і частки
# ============================================================

# Варіант 1 — Київ
VARIANT = 1
CITY = "Київ"
JULY_TEMP = 21

# ============================================================
# ЗАВДАННЯ 1
# Побудова вибірки денних температур
# ============================================================

np.random.seed(VARIANT)

daily_temps = np.random.normal(
    loc=JULY_TEMP,
    scale=2.5,
    size=30
)

mean = daily_temps.mean()
s = daily_temps.std(ddof=1)
n = len(daily_temps)

print("=" * 65)
print("ПРАКТИЧНА РОБОТА №12")
print("Довірчі інтервали для середнього і частки")
print("=" * 65)

print(f"\nВаріант: {VARIANT}")
print(f"Місто: {CITY}")
print(f"Липнева середньомісячна температура: {JULY_TEMP} °C")

print("\n" + "=" * 65)
print("ЗАВДАННЯ 1. Вибірка денних температур")
print("=" * 65)

print("\nМасив денних температур:")
print(np.round(daily_temps, 2))

print(f"\nКількість спостережень n: {n}")
print(f"Середнє: {mean:.4f} °C")
print(f"Вибіркове стандартне відхилення s: {s:.4f} °C")


# ============================================================
# ЗАВДАННЯ 2
# Довірчий інтервал для середньої температури
# ============================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 2. Довірчий інтервал для середньої")
print("=" * 65)

se = s / np.sqrt(n)

ci_mean = stats.t.interval(
    0.95,
    df=n - 1,
    loc=mean,
    scale=se
)

print(f"\nСтандартна похибка SE: {se:.4f}")

print(f"\n95% довірчий інтервал:")
print(f"Нижня межа: {ci_mean[0]:.4f} °C")
print(f"Верхня межа: {ci_mean[1]:.4f} °C")

print(f"\nІнтервал: ({ci_mean[0]:.2f}; {ci_mean[1]:.2f}) °C")

print("""
Пояснення:
для побудови інтервалу використано t-розподіл,
оскільки справжнє стандартне відхилення генеральної
сукупності σ невідоме. Замість нього використовується
вибіркове стандартне відхилення s, а вибірка має лише
30 спостережень. Тому z-критичне значення тут
використовувати недоцільно.
""")


# ============================================================
# ЗАВДАННЯ 3
# Довірчий інтервал для частки
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 3. Довірчий інтервал для частки")
print("=" * 65)

# Дні, коли температура перевищила 21 °C
above = daily_temps > JULY_TEMP

p_hat = above.mean()

n_p = n * p_hat
n_1p = n * (1 - p_hat)

se_p = np.sqrt(
    p_hat * (1 - p_hat) / n
)

ci_prop = stats.norm.interval(
    0.95,
    loc=p_hat,
    scale=se_p
)

print(f"\nКількість днів вище {JULY_TEMP} °C: {above.sum()}")
print(f"Частка p̂: {p_hat:.4f}")
print(f"Частка у відсотках: {p_hat * 100:.2f}%")

print(f"\nn × p̂ = {n_p:.2f}")
print(f"n × (1 - p̂) = {n_1p:.2f}")

print("\nПеревірка умови нормального наближення:")

if n_p >= 5 and n_1p >= 5:
    print("Умова виконується: обидва значення ≥ 5.")
else:
    print("Умова НЕ виконується: нормальне наближення ненадійне.")

print(f"\n95% довірчий інтервал для частки:")
print(f"Нижня межа: {ci_prop[0]:.4f}")
print(f"Верхня межа: {ci_prop[1]:.4f}")

print(
    f"\nІнтервал: ({ci_prop[0]:.4f}; {ci_prop[1]:.4f})"
)

print(f"\nЧи входить теоретичне значення 0.5 до інтервалу?")

if ci_prop[0] <= 0.5 <= ci_prop[1]:
    print("Так, 0.5 входить до довірчого інтервалу.")
else:
    print("Ні, 0.5 не входить до довірчого інтервалу.")

print("""
Пояснення:
вибірка складається лише з 30 спостережень, тому
конкретна випадкова реалізація може дати частку,
яка відрізняється від теоретичних 0.5.

95% довірчий інтервал не гарантує, що кожен окремий
інтервал міститиме теоретичне значення. При повторенні
процедури приблизно 95% побудованих інтервалів
накриватимуть справжню частку, а близько 5% — ні.
""")


# ============================================================
# ЗАВДАННЯ 4
# Ширина інтервалу при різних рівнях довіри
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 4. Ширина інтервалу при різних рівнях довіри")
print("=" * 65)

confidence_levels = [0.90, 0.95, 0.99]

print("\n{:>15} {:>15} {:>15} {:>15}".format(
    "Рівень", "Нижня межа", "Верхня межа", "Ширина"
))
print("-" * 65)

for confidence in confidence_levels:

    ci = stats.t.interval(
        confidence,
        df=n - 1,
        loc=mean,
        scale=se
    )

    width = ci[1] - ci[0]

    print(
        f"{confidence * 100:>14.0f}% "
        f"{ci[0]:>15.4f} "
        f"{ci[1]:>15.4f} "
        f"{width:>15.4f}"
    )

print("""
Висновок:
зі збільшенням рівня довіри з 90% до 95% і 99%
довірчий інтервал стає ширшим.

Щоб отримати вужчий інтервал при тому самому
рівні довіри 99%, потрібно збільшити розмір вибірки n.
Зі збільшенням n стандартна похибка s/√n зменшується,
тому інтервал стає вужчим.
""")


# ============================================================
# ЗАВДАННЯ 5
# Правильна інтерпретація 95% довірчого інтервалу
# ============================================================

print("=" * 65)
print("ЗАВДАННЯ 5. Інтерпретація результату")
print("=" * 65)

print(f"""
Отриманий 95% довірчий інтервал для середньої температури:
({ci_mean[0]:.2f}; {ci_mean[1]:.2f}) °C.

Якби ми багато разів повторювали процедуру формування
вибірки з 30 спостережень і кожного разу будували
95% довірчий інтервал тим самим способом, приблизно
95% отриманих інтервалів містили б справжнє середнє
генеральної сукупності.

Для конкретного вже побудованого інтервалу не слід
говорити, що ймовірність потрапляння справжнього
середнього в нього дорівнює 95%.
""")


