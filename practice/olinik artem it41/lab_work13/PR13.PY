import numpy as np
from scipy import stats

# ============================================================
# ПРАКТИЧНА РОБОТА №13
# Точкові оцінки та перевірка гіпотез
# ============================================================

variant = 1
city = "Київ"
july_temp = 21
mu0 = 20.0
alpha = 0.05

# ============================================================
# ЗАВДАННЯ 1. Вибірка і точкові оцінки
# ============================================================

np.random.seed(variant)

daily_temps = np.random.normal(
    loc=july_temp,
    scale=2.5,
    size=30
)

n = len(daily_temps)
mean = daily_temps.mean()
s = daily_temps.std(ddof=1)

print("=" * 65)
print("ПРАКТИЧНА РОБОТА №13")
print("Точкові оцінки та перевірка гіпотез")
print("=" * 65)

print()
print(f"Варіант: {variant}")
print(f"Місто: {city}")
print(f"Липнева температура: {july_temp} °C")
print(f"Стара норма μ0: {mu0:.1f} °C")

print()
print("=" * 65)
print("ЗАВДАННЯ 1. Вибірка і точкові оцінки")
print("=" * 65)

print()
print("Масив денних температур:")
print(np.round(daily_temps, 2))

print()
print(f"Кількість спостережень n: {n}")
print(f"Середнє вибірки x̄: {mean:.4f} °C")
print(f"Вибіркове стандартне відхилення s: {s:.4f} °C")

# ============================================================
# ЗАВДАННЯ 2. Формулювання H0 і H1
# ============================================================

print()
print("=" * 65)
print("ЗАВДАННЯ 2. Формулювання H0 і H1")
print("=" * 65)

print()
print("H0: μ = 20.0 °C — стара норма правильна.")
print("H1: μ ≠ 20.0 °C — стара норма більше не відповідає дійсності.")

print()
print("Обрано двобічний тест, оскільки нас цікавить")
print("будь-яке відхилення від старої норми — як у більший,")
print("так і в менший бік.")

# ============================================================
# ЗАВДАННЯ 3. z-статистика і p-value
# ============================================================

se = s / np.sqrt(n)
z = (mean - mu0) / se

# двобічний тест
p_value = 2 * (1 - stats.norm.cdf(abs(z)))

print()
print("=" * 65)
print("ЗАВДАННЯ 3. z-статистика і p-value")
print("=" * 65)

print()
print(f"Стандартна похибка SE: {se:.4f}")
print(f"z-статистика: {z:.4f}")
print(f"p-value: {p_value:.6f}")

# ============================================================
# ЗАВДАННЯ 4. Рішення при alpha = 0.05
# ============================================================

print()
print("=" * 65)
print("ЗАВДАННЯ 4. Рішення при α = 0.05")
print("=" * 65)

print()
print(f"α = {alpha}")
print(f"p-value = {p_value:.6f}")

if p_value < alpha:
    decision = "Відхиляємо H0."
    conclusion = (
        f"Отримані дані дають статистично значущі підстави "
        f"вважати, що середня липнева температура в місті {city} "
        f"відрізняється від старої норми {mu0:.1f} °C."
    )
else:
    decision = "Не відхиляємо H0."
    conclusion = (
        f"Отримані дані не дають достатніх статистичних підстав "
        f"вважати, що середня липнева температура в місті {city} "
        f"відрізняється від старої норми {mu0:.1f} °C."
    )

print()
print(decision)
print(conclusion)

# ============================================================
# ЗАВДАННЯ 5. Перевірка через довірчий інтервал
# ============================================================

ci_low = mean - 1.96 * se
ci_high = mean + 1.96 * se

print()
print("=" * 65)
print("ЗАВДАННЯ 5. 95% довірчий інтервал")
print("=" * 65)

print()
print(f"Нижня межа: {ci_low:.4f} °C")
print(f"Верхня межа: {ci_high:.4f} °C")
print(f"95% довірчий інтервал: ({ci_low:.4f}; {ci_high:.4f}) °C")

if ci_low <= mu0 <= ci_high:
    print()
    print(f"Стара норма μ0 = {mu0:.1f} °C входить у довірчий інтервал.")
    print("Висновок узгоджується з тестом: H0 не відхиляємо.")
else:
    print()
    print(f"Стара норма μ0 = {mu0:.1f} °C НЕ входить у довірчий інтервал.")
    print("Висновок узгоджується з тестом: H0 відхиляємо.")

# ============================================================
# ПОМИЛКИ I ТА II РОДУ
# ============================================================

print()
print("=" * 65)
print("ПОМИЛКИ I ТА II РОДУ")
print("=" * 65)

print()
print("Помилка I роду:")
print(
    "відхилити H0 і зробити висновок, що стара норма "
    "20.0 °C більше не правильна, хоча насправді вона правильна."
)

print()
print("Помилка II роду:")
print(
    "не відхилити H0 і залишити стару норму 20.0 °C, "
    "хоча насправді середня температура вже змінилася."
)

print()
print(
    "Для кліматологів помилка II роду може бути особливо важливою, "
    "оскільки невиявлення реальної зміни клімату може призвести "
    "до використання застарілих кліматичних норм."
)

# ============================================================
# КОНТРОЛЬНІ ПИТАННЯ
# ============================================================

print()
print("=" * 65)
print("КОНТРОЛЬНІ ПИТАННЯ")
print("=" * 65)

print()
print("1. Що означає p-value?")
print(
    "p-value — це ймовірність отримати таке саме або ще більш "
    "екстремальне відхилення від H0, якщо H0 справді правильна. "
    "Це НЕ ймовірність того, що H0 правильна."
)

print()
print("2. Чому тест обирають до перегляду результату?")
print(
    "Тип тесту потрібно визначити заздалегідь, щоб не підлаштовувати "
    "статистичний аналіз під отримані дані та не збільшувати ризик "
    "помилки I роду."
)

print()
print("3. Помилки I та II роду:")
print(
    "Помилка I роду — помилково відхилити правильну стару норму. "
    "Помилка II роду — не відхилити стару норму, хоча вона вже "
    "не відповідає реальному середньому."
)

print()
print("4. Узгодження тесту і довірчого інтервалу:")
print(
    "При α = 0.05 двобічний тест і 95% довірчий інтервал "
    "повинні давати узгоджений висновок. Якщо μ0 не входить "
    "до 95% інтервалу, H0 відхиляється; якщо входить — H0 "
    "не відхиляється."
)

# ============================================================
# ПІДСУМОК
# ============================================================

print()
print("=" * 65)
print("ПІДСУМОК")
print("=" * 65)

print()
print(f"Місто: {city}")
print(f"Варіант: {variant}")
print(f"Стара норма μ0: {mu0:.1f} °C")
print(f"Середнє вибірки: {mean:.4f} °C")
print(f"Стандартне відхилення: {s:.4f} °C")
print(f"Стандартна похибка: {se:.4f}")
print(f"z-статистика: {z:.4f}")
print(f"p-value: {p_value:.6f}")
print(f"95% ДІ: ({ci_low:.4f}; {ci_high:.4f}) °C")
print()
print(decision)
print()
print("Практична робота №13 виконана повністю.")