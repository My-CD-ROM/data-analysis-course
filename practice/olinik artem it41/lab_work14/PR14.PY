import numpy as np
from scipy import stats

print("=" * 65)
print("ПРАКТИЧНА РОБОТА №14")
print("Параметричні критерії: t-критерій та порівняння дисперсій")
print("=" * 65)

# Варіант 1 — Київ
kyiv = np.array([84, 82, 78, 70, 65, 63, 61, 63, 68, 75, 81, 85])
norm = 74

# Львів — інший регіон (Захід)
lviv = np.array([85, 83, 80, 73, 68, 65, 63, 65, 70, 77, 82, 86])

# Одеса — інший регіон (Південь)
odesa = np.array([82, 80, 78, 74, 71, 69, 67, 68, 72, 76, 80, 83])

# Амплітуда ранок-вечір
amplitude = np.array([3, 3, 4, 5, 6, 7, 7, 7, 6, 5, 4, 3])

alpha = 0.05


# ================================================================
# ЗАВДАННЯ 1
# ================================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 1. Одновибірковий t-критерій")
print("=" * 65)

mean_kyiv = kyiv.mean()
std_kyiv = kyiv.std(ddof=1)

t_stat, p_value = stats.ttest_1samp(kyiv, popmean=norm)

print(f"Місто: Київ")
print(f"Норма: {norm}%")
print(f"Середнє: {mean_kyiv:.4f}%")
print(f"Стандартне відхилення: {std_kyiv:.4f}%")
print(f"t-статистика: {t_stat:.4f}")
print(f"p-value: {p_value:.6f}")

print("\nH0: μ = 74% — середня вологість відповідає нормі.")
print("H1: μ ≠ 74% — середня вологість відрізняється від норми.")

if p_value < alpha:
    print("\nРішення: H0 відхиляємо.")
    print("Є статистично значущі підстави вважати,")
    print("що середня вологість Києва відрізняється від норми.")
else:
    print("\nРішення: H0 не відхиляємо.")
    print("Немає достатніх статистичних підстав вважати,")
    print("що середня вологість Києва відрізняється від норми.")


# ================================================================
# ЗАВДАННЯ 2
# ================================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 2. Ручна перевірка t-статистики")
print("=" * 65)

n = len(kyiv)

t_manual = (mean_kyiv - norm) / (std_kyiv / np.sqrt(n))

print(f"Середнє x̄: {mean_kyiv:.4f}")
print(f"Норма μ0: {norm:.4f}")
print(f"s: {std_kyiv:.4f}")
print(f"n: {n}")
print(f"t вручну: {t_manual:.4f}")
print(f"t з ttest_1samp: {t_stat:.4f}")

print("\nРезультати збігаються з округленням.")


# ================================================================
# ЗАВДАННЯ 3
# ================================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 3. Київ проти Львова")
print("=" * 65)

lev_stat, lev_p = stats.levene(kyiv, lviv)

print("Київ: Центр")
print("Львів: Захід")

print(f"\nLevene statistic: {lev_stat:.4f}")
print(f"Levene p-value: {lev_p:.6f}")

if lev_p < alpha:
    equal_var = False
    print("\nДисперсії статистично відрізняються.")
    print("Використовуємо Welch t-test: equal_var=False.")
else:
    equal_var = True
    print("\nНемає статистичних підстав вважати дисперсії різними.")
    print("Використовуємо стандартний t-test: equal_var=True.")

t_stat_3, p_value_3 = stats.ttest_ind(
    kyiv,
    lviv,
    equal_var=equal_var
)

print(f"\nt-статистика: {t_stat_3:.4f}")
print(f"p-value: {p_value_3:.6f}")

if p_value_3 < alpha:
    print("\nВисновок: середні значення вологості Києва")
    print("та Львова статистично значуще відрізняються.")
else:
    print("\nВисновок: статистично значущої різниці")
    print("між середньою вологістю Києва та Львова не виявлено.")


# ================================================================
# ЗАВДАННЯ 4
# ================================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 4. Київ проти Одеси")
print("=" * 65)

lev_stat_4, lev_p_4 = stats.levene(kyiv, odesa)

print("Київ: Центр")
print("Одеса: Південь")

print(f"\nLevene statistic: {lev_stat_4:.4f}")
print(f"Levene p-value: {lev_p_4:.6f}")

if lev_p_4 < alpha:
    equal_var_4 = False
    print("\nДисперсії статистично різні.")
    print("Використовуємо Welch t-test: equal_var=False.")
else:
    equal_var_4 = True
    print("\nДисперсії статистично не відрізняються.")
    print("Використовуємо стандартний t-test: equal_var=True.")

t_stat_4, p_value_4 = stats.ttest_ind(
    kyiv,
    odesa,
    equal_var=equal_var_4
)

print(f"\nt-статистика: {t_stat_4:.4f}")
print(f"p-value: {p_value_4:.6f}")

if p_value_4 < alpha:
    print("\nВисновок: середні значення вологості Києва")
    print("та Одеси статистично значуще відрізняються.")
else:
    print("\nВисновок: статистично значущої різниці")
    print("між середньою вологістю Києва та Одеси не виявлено.")


# ================================================================
# ЗАВДАННЯ 5
# ================================================================

print("\n" + "=" * 65)
print("ЗАВДАННЯ 5. Парний t-критерій: ранок проти вечора")
print("=" * 65)

evening = kyiv - amplitude

print("Ранкові значення:")
print(kyiv)

print("\nВечірні значення:")
print(evening)

t_rel, p_rel = stats.ttest_rel(kyiv, evening)

print(f"\nt-статистика: {t_rel:.4f}")
print(f"p-value: {p_rel:.8f}")

if p_rel < alpha:
    print("\nРішення: H0 відхиляємо.")
    print("Різниця між ранковою та вечірньою вологістю")
    print("є статистично значущою.")
else:
    print("\nРішення: H0 не відхиляємо.")
    print("Статистично значущої різниці не виявлено.")

print("\nПарний критерій використовується тому, що")
print("ранкове та вечірнє значення належать одному й тому")
print("самому місяцю. При аналізі різниць усувається")
print("вплив індивідуальних особливостей кожної пари.")


# ================================================================
# ПІДСУМОК
# ================================================================

print("\n" + "=" * 65)
print("ПІДСУМОК")
print("=" * 65)

print("Місто: Київ")
print("Варіант: 1")

print(f"\nЗавдання 1: t = {t_stat:.4f}, p = {p_value:.6f}")
print(f"Завдання 2: ручне t = {t_manual:.4f}")
print(f"Завдання 3: Levene p = {lev_p:.6f}, t-test p = {p_value_3:.6f}")
print(f"Завдання 4: Levene p = {lev_p_4:.6f}, Welch p = {p_value_4:.6f}")
print(f"Завдання 5: paired t = {t_rel:.4f}, p = {p_rel:.8f}")

print("\nПрактична робота №14 виконана повністю.")