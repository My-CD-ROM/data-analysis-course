print("\n" + "=" * 70)
print("ЗАВДАННЯ 5. ВЛАСНА ЗАЯВЛЕНА ПРОПОРЦІЯ")
print("=" * 70)

# Обґрунтоване припущення:
# 20% холодніше, 60% звичайно, 20% тепліше
hypothesis = {
    "холодніше": 0.20,
    "звичайно": 0.60,
    "тепліше": 0.20
}

observed_norm = climate[
    "відхилення_від_норми"
].value_counts().reindex(
    norm_order,
    fill_value=0
)

n = len(climate)

expected_norm = [
    hypothesis["холодніше"] * n,
    hypothesis["звичайно"] * n,
    hypothesis["тепліше"] * n
]

result_norm = chisquare(
    f_obs=observed_norm,
    f_exp=expected_norm
)

print("\nНульова гіпотеза H0:")
print(
    "Розподіл відхилень від норми відповідає пропорції "
    "20% / 60% / 20%."
)

print("\nФактичні частоти:")
print(observed_norm)

print("\nОчікувані частоти:")
print(pd.Series(
    expected_norm,
    index=norm_order
))

print(f"\nχ² = {result_norm.statistic:.4f}")
print(f"p-value = {result_norm.pvalue:.10f}")

print("\nВисновок:")

if result_norm.pvalue < 0.05:
    print(
        "p-value < 0.05, тому H0 відхиляємо. Фактичний "
        "розподіл статистично відрізняється від заявленої "
        "пропорції 20% / 60% / 20%."
    )
else:
    print(
        "p-value >= 0.05, тому немає достатніх підстав "
        "відхилити H0. Фактичний розподіл узгоджується "
        "із заявленою пропорцією 20% / 60% / 20%."
    )

print("""
Обрана пропорція є обґрунтованою, оскільки категорія
"звичайно" визначається температурним відхиленням у межах
±3°C від середньорічної температури. Через сезонні коливання
очікується, що частина спостережень буде "холодніше" або
"тепліше", а частина залишатиметься в межах звичайного
відхилення. Тому пропорція 20% / 60% / 20% є змістовною
гіпотезою для перевірки, а не випадковим набором чисел.
""")


