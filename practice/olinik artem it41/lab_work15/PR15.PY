import numpy as np
import pandas as pd
from scipy.stats import chi2_contingency, chisquare

# ============================================================
# ПРАКТИЧНА РОБОТА №15
# Критерії узгодженості й таблиці спряженості: χ²
# ============================================================

# Варіант 1 — Київ
CITY = "Київ"
BASE_TEMP = 9.5
AMPLITUDE = 14

np.random.seed(42)

# ============================================================
# ПОБУДОВА НАБОРУ ДАНИХ
# ============================================================

def season(month):
    if month in (12, 1, 2):
        return "зима"
    if month in (3, 4, 5):
        return "весна"
    if month in (6, 7, 8):
        return "літо"
    return "осінь"


rows = []

for year in [2021, 2022, 2023, 2024]:
    for month in range(1, 13):

        seasonal = AMPLITUDE * np.cos(
            (month - 7) / 12 * 2 * np.pi
        )

        noise = np.random.normal(0, 1.0)

        temp = round(BASE_TEMP + seasonal + noise, 1)

        diff = temp - BASE_TEMP

        if diff < -3:
            norm_cat = "холодніше"
        elif diff > 3:
            norm_cat = "тепліше"
        else:
            norm_cat = "звичайно"

        rows.append({
            "місто": CITY,
            "рік": year,
            "місяць": month,
            "температура": temp,
            "сезон": season(month),
            "відхилення_від_норми": norm_cat
        })

climate = pd.DataFrame(rows)


print("=" * 70)
print("ПРАКТИЧНА РОБОТА №15")
print("Критерії узгодженості й таблиці спряженості: критерій χ²")
print("=" * 70)

print(f"\nСтудент: Artem Oliynyk")
print(f"Варіант: 1")
print(f"Місто: {CITY}")
print(f"Середньорічна температура: {BASE_TEMP} °C")
print(f"Сезонна амплітуда: {AMPLITUDE} °C")

print("\nПерші 10 рядків набору:")
print(climate.head(10))

print(f"\nКількість рядків: {len(climate)}")


# ============================================================
# ЗАВДАННЯ 1
# ТАБЛИЦЯ СПРЯЖЕНОСТІ
# ============================================================

print("\n" + "=" * 70)
print("ЗАВДАННЯ 1. ТАБЛИЦЯ СПРЯЖЕНОСТІ")
print("=" * 70)

table = pd.crosstab(
    climate["сезон"],
    climate["відхилення_від_норми"]
)

# правильний порядок
season_order = ["зима", "весна", "літо", "осінь"]
norm_order = ["холодніше", "звичайно", "тепліше"]

table = table.reindex(
    index=season_order,
    columns=norm_order,
    fill_value=0
)

print("\nФактична таблиця спряженості:")
print(table)

print("\nНормалізована таблиця (normalize='index'):")
table_normalized = pd.crosstab(
    climate["сезон"],
    climate["відхилення_від_норми"],
    normalize="index"
).reindex(
    index=season_order,
    columns=norm_order,
    fill_value=0
)

print(table_normalized.round(3))

# Найчастіша комбінація
max_cell = table.stack().idxmax()
max_value = table.loc[max_cell]

print("\nНайчастіша комбінація:")
print(f"Сезон: {max_cell[0]}")
print(f"Відхилення: {max_cell[1]}")
print(f"Кількість: {max_value}")

print("""
Пояснення:
Найчастіша комбінація відповідає сезонному характеру температур.
Влітку температура переважно вища за середньорічну,
а взимку — нижча. Нормалізована таблиця показує частки
категорій усередині кожного сезону. Сума кожного рядка
дорівнює 1 (або 100%), тому сезони з різною кількістю
спостережень можна зручно порівнювати між собою.
""")


# ============================================================
# ЗАВДАННЯ 2
# КРИТЕРІЙ НЕЗАЛЕЖНОСТІ
# ============================================================

print("\n" + "=" * 70)
print("ЗАВДАННЯ 2. КРИТЕРІЙ НЕЗАЛЕЖНОСТІ χ²")
print("=" * 70)

chi2, pvalue, dof, expected = chi2_contingency(table)

expected_df = pd.DataFrame(
    expected,
    index=table.index,
    columns=table.columns
)

print(f"\nСтатистика χ²: {chi2:.4f}")
print(f"p-value: {pvalue:.10f}")
print(f"Ступені свободи: {dof}")

print("\nОчікувані частоти:")
print(expected_df.round(2))

# найбільше абсолютне відхилення
difference = (table - expected_df).abs()

max_difference_cell = difference.stack().idxmax()
max_difference = difference.loc[max_difference_cell]

print("\nНайбільша різниця між observed та expected:")
print(f"Клітинка: {max_difference_cell}")
print(f"Фактична частота: {table.loc[max_difference_cell]}")
print(f"Очікувана частота: {expected_df.loc[max_difference_cell]:.2f}")
print(f"Абсолютна різниця: {max_difference:.2f}")

print("\nВисновок при α = 0.05:")

if pvalue < 0.05:
    print(
        "p-value < 0.05, тому нульову гіпотезу про незалежність "
        "відхиляємо. Є статистично значущий зв'язок між сезоном "
        "і відхиленням від норми."
    )
else:
    print(
        "p-value >= 0.05, тому немає достатніх підстав "
        "відхилити нульову гіпотезу про незалежність."
    )


# ============================================================
# ЗАВДАННЯ 3
# ПЕРЕВІРКА УМОВИ ЗАСТОСОВНОСТІ
# ============================================================

print("\n" + "=" * 70)
print("ЗАВДАННЯ 3. ПЕРЕВІРКА УМОВИ ЗАСТОСОВНОСТІ")
print("=" * 70)

min_expected = expected.min()

print(f"\nМінімальна очікувана частота: {min_expected:.2f}")

low_cells = []

for row in expected_df.index:
    for col in expected_df.columns:
        value = expected_df.loc[row, col]

        if value < 5:
            low_cells.append((row, col, value))

if len(low_cells) == 0:

    print("Усі очікувані частоти >= 5.")
    print("Умова застосовності критерію χ² виконується.")
    print("Об'єднання категорій не потрібне.")

else:

    print("Є клітинки з очікуваною частотою < 5:")

    for row, col, value in low_cells:
        print(
            f"  {row} + {col}: {value:.2f}"
        )

    print("""
Для виконання умови застосовності можна об'єднати
рідкісні категорії. Наприклад, "холодніше" та "звичайно"
можна об'єднати в категорію "не тепліше".
""")

    climate["об'єднана_категорія"] = climate[
        "відхилення_від_норми"
    ].replace({
        "холодніше": "не тепліше",
        "звичайно": "не тепліше"
    })

    table_merged = pd.crosstab(
        climate["сезон"],
        climate["об'єднана_категорія"]
    )

    print("\nОб'єднана таблиця:")
    print(table_merged)

    chi2_m, pvalue_m, dof_m, expected_m = chi2_contingency(
        table_merged
    )

    print("\nПовторний тест:")
    print(f"χ² = {chi2_m:.4f}")
    print(f"p-value = {pvalue_m:.10f}")
    print(f"dof = {dof_m}")

    print("\nОчікувані частоти після об'єднання:")
    print(
        pd.DataFrame(
            expected_m,
            index=table_merged.index,
            columns=table_merged.columns
        ).round(2)
    )


# ============================================================
# ЗАВДАННЯ 4
# КРИТЕРІЙ УЗГОДЖЕНОСТІ ДЛЯ СЕЗОНІВ
# ============================================================

print("\n" + "=" * 70)
print("ЗАВДАННЯ 4. КРИТЕРІЙ УЗГОДЖЕНОСТІ ДЛЯ СЕЗОНІВ")
print("=" * 70)

season_counts = climate["сезон"].value_counts().reindex(
    season_order,
    fill_value=0
)

print("\nФактична кількість кожного сезону:")
print(season_counts)

expected_seasons = [12, 12, 12, 12]

result_seasons = chisquare(
    f_obs=season_counts,
    f_exp=expected_seasons
)

print("\nОчікувані частоти:")
print(expected_seasons)

print(f"\nχ² = {result_seasons.statistic:.4f}")
print(f"p-value = {result_seasons.pvalue:.10f}")

print("\nВисновок:")

if result_seasons.pvalue < 0.05:
    print(
        "p-value < 0.05, тому розподіл сезонів статистично "
        "відрізняється від рівномірного."
    )
else:
    print(
        "p-value >= 0.05, тому немає підстав вважати, "
        "що розподіл сезонів відрізняється від рівномірного."
    )

print("""
Цей результат очікуваний, оскільки в кожному з чотирьох
років є рівно по три місяці кожного сезону. Тому кожен сезон
має однакову кількість спостережень — 12 із 48, тобто 25%.
""")


