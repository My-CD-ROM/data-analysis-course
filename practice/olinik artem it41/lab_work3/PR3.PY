import pandas as pd

# ============================================================
# ПРАКТИЧНА РОБОТА 3
# Приведення до tidy data
# Варіант 1 — Київ
# ============================================================

print("=" * 60)
print("ПРАКТИЧНА РОБОТА 3")
print("Приведення до tidy data")
print("Варіант 1 — Київ")
print("=" * 60)

# ============================================================
# ЗАВДАННЯ 1. ПОБУДОВА WIDE-ТАБЛИЦІ
# ============================================================

wide = pd.DataFrame({
    "місто": ["Київ"],
    "Січ": [78],
    "Лют": [74],
    "Бер": [68],
    "Кві": [58],
    "Тра": [50],
    "Чер": [44],
    "Лип": [40],
    "Сер": [42],
    "Вер": [52],
    "Жов": [66],
    "Лис": [76],
    "Гру": [82]
})

print("\n" + "=" * 60)
print("ЗАВДАННЯ 1. WIDE-ТАБЛИЦЯ")
print("=" * 60)

print("\nПочаткова wide-таблиця:")
print(wide)

print("\nФорма таблиці:")
print(wide.shape)

# ============================================================
# ЗАВДАННЯ 2. WIDE -> TIDY
# ============================================================

tidy = wide.melt(
    id_vars="місто",
    var_name="місяць",
    value_name="хмарність"
)

print("\n" + "=" * 60)
print("ЗАВДАННЯ 2. ПЕРЕТВОРЕННЯ WIDE -> TIDY")
print("=" * 60)

print("\nTidy-таблиця:")
print(tidy)

print("\nФорма tidy-таблиці:")
print(tidy.shape)

print("""
Пояснення:
У вихідній wide-таблиці було лише 1 рядок із містом,
а 12 місяців були окремими стовпцями.
Після melt() кожен місяць стає окремим рядком.
Тому отримуємо 12 рядків і 3 стовпці:
місто, місяць, хмарність.
""")

# ============================================================
# ЗАВДАННЯ 3. КЛАСИФІКАЦІЯ ЗМІННИХ
# ============================================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 3. КЛАСИФІКАЦІЯ ЗМІННИХ")
print("=" * 60)

print("""
місто — номінальна шкала.
Назва міста є категорією без числового порядку.

місяць — порядкова шкала.
Місяці мають природний порядок протягом року.

хмарність — шкала відношень.
Хмарність у відсотках має абсолютний нуль (0%),
а співвідношення значень має зміст.
Наприклад, 80% хмарності вдвічі більше за 40%.
""")

# ============================================================
# ЗАВДАННЯ 4. TIDY -> WIDE
# ============================================================

back = tidy.pivot(
    index="місто",
    columns="місяць",
    values="хмарність"
)

# Прибираємо назву осі columns для красивого виводу
back.columns.name = None

print("\n" + "=" * 60)
print("ЗАВДАННЯ 4. ЗВОРОТНЕ ПЕРЕТВОРЕННЯ")
print("=" * 60)

print("\nТаблиця після pivot():")
print(back)

print("\nПорівняння значень:")
print("Початкова таблиця:")
print(wide)

print("\nОтримана таблиця:")
print(back.reset_index())

# Перевірка значень
check = (
    wide.set_index("місто")
    .sort_index(axis=1)
    .equals(
        back.sort_index(axis=1)
    )
)

print("\nЧи збігаються таблиці?")
print(check)

# ============================================================
# ЗАВДАННЯ 5. CSV ТА JSON
# ============================================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 5. ЧИТАННЯ І ЗАПИС CSV ТА JSON")
print("=" * 60)

# Записуємо tidy-таблицю
tidy.to_csv(
    "variant.csv",
    index=False,
    encoding="utf-8-sig"
)

tidy.to_json(
    "variant.json",
    orient="records",
    force_ascii=False,
    indent=2
)

print("\nФайли створено:")
print("variant.csv")
print("variant.json")

# Читаємо CSV
reloaded_csv = pd.read_csv(
    "variant.csv",
    encoding="utf-8-sig"
)

# Читаємо JSON
reloaded_json = pd.read_json(
    "variant.json"
)

print("\nДані після читання CSV:")
print(reloaded_csv)

print("\nДані після читання JSON:")
print(reloaded_json)

# Перевірка
csv_equal = tidy.equals(reloaded_csv)
json_equal = tidy.equals(reloaded_json)

print("\nПеревірка CSV:")
print(csv_equal)

print("\nПеревірка JSON:")
print(json_equal)

# ============================================================
# ВМІСТ CSV
# ============================================================

print("\n" + "=" * 60)
print("ВМІСТ ФАЙЛУ variant.csv")
print("=" * 60)

with open("variant.csv", "r", encoding="utf-8-sig") as file:
    print(file.read())

# ============================================================
# ВМІСТ JSON
# ============================================================

print("\n" + "=" * 60)
print("ВМІСТ ФАЙЛУ variant.json")
print("=" * 60)

with open("variant.json", "r", encoding="utf-8") as file:
    print(file.read())

# ============================================================
# ПИСЬМОВІ ВІДПОВІДІ
# ============================================================

print("\n" + "=" * 60)
print("ПИСЬМОВІ ВІДПОВІДІ")
print("=" * 60)

print("""
1. Стовпець "місто" є номінальною шкалою,
тому що назви міст є категоріями без числового порядку.
"Хмарність" є шкалою відношень, тому що вона вимірюється
у відсотках, має абсолютний нуль і можна порівнювати
співвідношення значень.

2. Wide-таблиця з місяцями в окремих стовпцях
не є tidy, тому що одна змінна "місяць" розподілена
між назвами різних стовпців. Після melt() усі місяці
стають значеннями одного стовпця "місяць", а хмарність —
значеннями одного стовпця "хмарність".

3. CSV зберігає таблицю у вигляді текстових рядків
із розділювачами між значеннями. JSON має структурований
формат і зберігає кожен рядок як окремий об'єкт
із парами "назва: значення".
""")

print("\n" + "=" * 60)
print("ПРАКТИЧНУ РОБОТУ 3 ВИКОНАНО")
print("=" * 60)