print("ЗАВДАННЯ 4. ТИПИ ДАНИХ І КАТЕГОРІЇ")
print("=" * 60)

# Перетворення ціни в число
orders["ціна"] = (
    orders["ціна"]
    .astype(str)
    .str.replace(" грн", "", regex=False)
    .astype(float)
)

print("\nТип даних після перетворення ціни:")
print(orders["ціна"].dtype)

# Узгодження назв міста
orders["місто"] = (
    orders["місто"]
    .str.strip()
    .str.lower()
    .replace({
        "київ": "Київ"
    })
)

print("\nУнікальні назви міста після очищення:")
print(orders["місто"].unique())

print("\nОчищений набір:")
print(orders)

# ============================================================
# ЗАВДАННЯ 5. ВИКИДИ
# ============================================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 5. ВИКИДИ")
print("=" * 60)

# Обчислення квартилів
q1 = orders["ціна"].quantile(0.25)
q3 = orders["ціна"].quantile(0.75)

iqr = q3 - q1

lower = q1 - 1.5 * iqr
upper = q3 + 1.5 * iqr

print("\nQ1:")
print(q1)

print("\nQ3:")
print(q3)

print("\nIQR:")
print(iqr)

print("\nНижня межа:")
print(lower)

print("\nВерхня межа:")
print(upper)

# Пошук викидів
outliers = orders[
    (orders["ціна"] < lower) |
    (orders["ціна"] > upper)
]

print("\nЗначення поза межами IQR:")
print(outliers)

# Перевірка 8500
print("\nЧи є 8500 грн викидом?")
print(8500 < lower or 8500 > upper)

print("""
Пояснення щодо 8500 грн:

Значення 8500 грн я вважаю помилкою введення,
оскільки базова ціна товару становить 850 грн,
а 8500 грн рівно у 10 разів більше.

Для одного товару така різка відмінність без додаткового
пояснення виглядає як зайвий нуль у ціні. Тому це значення
доцільно вважати помилкою введення, а не реальним замовленням.
""")

# Видаляємо викид
orders_clean = orders[
    (orders["ціна"] >= lower) &
    (orders["ціна"] <= upper)
].copy()

print("\nНабір після видалення викиду:")
print(orders_clean)

