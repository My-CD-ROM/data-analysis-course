import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

print("=" * 60)
print("ПРАКТИЧНА РОБОТА 5")
print("Шкали вимірювання і частотний розподіл")
print("Варіант 1 — Київ")
print("=" * 60)


# ============================================================
# ДАНІ
# ============================================================

months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер",
          "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

precip = pd.Series(
    [47, 44, 38, 43, 60, 78, 88, 70, 48, 41, 47, 50],
    index=months,
    name="Опади"
)

print("\nДАНІ ПРО ОПАДИ В КИЄВІ:")
print(precip)


# ============================================================
# ЗАВДАННЯ 1. КЛАСИФІКАЦІЯ ЗМІННИХ
# ============================================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 1. КЛАСИФІКАЦІЯ ЗМІННИХ")
print("=" * 60)

print("""
1. Місто — номінальна шкала.
Назва міста є категорією без числового порядку.
Для міста коректною мірою положення є тільки мода.

2. Номер місяця — порядкова шкала.
Місяці мають природний порядок, але не існує
природного нульового місяця як відсутності місяця.
Тому в цій роботі вважаємо номер місяця порядковою змінною.
Для неї коректною мірою є медіана або мода.

3. Кількість опадів — відносна шкала.
Вона має абсолютний нуль: 0 мм означає відсутність опадів.
Можна коректно порівнювати співвідношення значень.
Для неї можна використовувати середнє, медіану і моду.
""")


# ============================================================
# ЗАВДАННЯ 2. ВАРІАЦІЙНИЙ РЯД І ЧАСТОТНА ТАБЛИЦЯ
# ============================================================

print("=" * 60)
print("ЗАВДАННЯ 2. ВАРІАЦІЙНИЙ РЯД І ЧАСТОТНА ТАБЛИЦЯ")
print("=" * 60)

# 1. Варіаційний ряд
variation_series = np.sort(precip.values)

print("\n1. Варіаційний ряд:")
print(variation_series)


# 2. Чотири інтервали
# Мінімум = 38, максимум = 88
# Обираємо інтервали:
# 38–49, 50–61, 62–73, 74–88

bins = [37, 49, 61, 73, 88]
labels = ["38–49", "50–61", "62–73", "74–88"]

groups = pd.cut(
    precip,
    bins=bins,
    labels=labels,
    include_lowest=True
)

freq = groups.value_counts().sort_index()
relative = (freq / len(precip) * 100).round(1)
cumulative = freq.cumsum()

frequency_table = pd.DataFrame({
    "Інтервал": labels,
    "Абсолютна частота": freq.values,
    "Відносна частота (%)": relative.values,
    "Накопичена частота": cumulative.values
})

print("\n2. Частотна таблиця:")
print(frequency_table.to_string(index=False))


# 3. Частка до межі третього інтервалу
third_cumulative = cumulative.iloc[2]
third_percent = third_cumulative / len(precip) * 100

print("\n3. Накопичена частота на межі третього інтервалу:")
print(f"{third_cumulative} із {len(precip)} місяців")
print(f"Це {third_percent:.1f}% року.")

print("""
Пояснення:
До межі третього інтервалу входять усі місяці,
у яких кількість опадів не перевищує 73 мм.
Таких місяців 9 із 12, тобто 75%.
""")


# ============================================================
# ЗАВДАННЯ 3. ГІСТОГРАМИ
# ============================================================

print("=" * 60)
print("ЗАВДАННЯ 3. ГІСТОГРАМИ")
print("=" * 60)

n = len(precip)

sqrt_bins = round(np.sqrt(n))
sturges_bins = round(1 + np.log2(n))

print(f"\nКількість спостережень n = {n}")
print(f"Правило √n: приблизно {sqrt_bins} інтервалів")
print(f"Правило Стерджеса: приблизно {sturges_bins} інтервалів")

print("""
Побудовано три гістограми:
1. За замовчуванням.
2. З 3 інтервалами.
3. З 10 інтервалами.

Для 12 значень найкраще підходить гістограма
з помірною кількістю інтервалів — приблизно 3–4.
Вона не надто згладжує дані і водночас
не робить розподіл надмірно подрібненим.
""")


# Гістограма за замовчуванням
plt.figure()
plt.hist(precip, edgecolor="black")
plt.title("Гістограма опадів у Києві — за замовчуванням")
