plt.title("Гістограма опадів у Києві — 3 інтервали")
plt.xlabel("Опади, мм")
plt.ylabel("Частота")
plt.grid(axis="y", alpha=0.3)
plt.show()


# 10 bins
plt.figure()
plt.hist(precip, bins=10, edgecolor="black")
plt.title("Гістограма опадів у Києві — 10 інтервалів")
plt.xlabel("Опади, мм")
plt.ylabel("Частота")
plt.grid(axis="y", alpha=0.3)
plt.show()


