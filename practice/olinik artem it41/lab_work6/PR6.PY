print("=" * 60)

minimum = humidity.min()
maximum = humidity.max()

rozmah = maximum - minimum

variance_sample = humidity.var(ddof=1)
variance_population = humidity.var(ddof=0)

std_sample = humidity.std(ddof=1)
std_population = humidity.std(ddof=0)

q1 = humidity.quantile(0.25)
q3 = humidity.quantile(0.75)

iqr = q3 - q1

mean_value = humidity.mean()

cv = std_sample / mean_value * 100

print("\nРозмах:")
print(rozmah)

print("\nДисперсія ddof=1:")
print(round(variance_sample, 4))

print("\nДисперсія ddof=0:")
print(round(variance_population, 4))

print("\nСтандартне відхилення ddof=1:")
print(round(std_sample, 4))

print("\nСтандартне відхилення ddof=0:")
print(round(std_population, 4))

print("\nQ1:")
print(q1)

print("\nQ3:")
print(q3)

print("\nIQR:")
print(iqr)

print("\nКоефіцієнт варіації:")
print(round(cv, 2), "%")

print("\nПеревірка Q1 і Q3:")
print("Q1 з describe():", humidity.describe()["25%"])
print("Q1 ручне:", q1)
print("Q3 з describe():", humidity.describe()["75%"])
print("Q3 ручне:", q3)

