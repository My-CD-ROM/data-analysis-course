axes[1].set_xlabel("Продажі, шт./день")
axes[1].set_ylabel("Кількість днів")
axes[1].set_title("Спотворена гістограма")

plt.tight_layout()
plt.show()

print("""
Спотворення:
У другому графіку вісь Y починається не з нуля, а зі значення 2.
Через це різниця між висотами стовпців здається більшою, ніж вона
є насправді. Числові значення залишаються правильними, але
візуальне сприйняття розподілу стає оманливим.
""")


