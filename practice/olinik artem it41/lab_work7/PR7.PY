import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

print("=" * 60)
print("ПРАКТИЧНА РОБОТА 7")
print("Візуалізація: Figure і Axes, гістограма, boxplot, scatter")
print("Варіант 1 — Київ")
print("=" * 60)


# ============================================================
# ЗАВДАННЯ 1. ПОБУДОВА ВЛАСНОГО НАБОРУ
# ============================================================

np.random.seed(1)

days = np.arange(1, 31)

# Кожен 6-й і 7-й день умовно вважаємо вихідним
weekend = (days % 7 == 6) | (days % 7 == 0)

# Базова температура Києва = 3 °C
temperature = np.round(3 + np.random.uniform(-3, 3, 30), 1)

# Базові продажі = 40 шт./день
sales = 40 + np.random.randint(-6, 7, 30)

# У вихідні продажі на 15–25% більші
weekend_multiplier = np.ones(30)

for i in range(30):
    if weekend[i]:
        weekend_multiplier[i] = np.random.uniform(1.15, 1.25)

sales = np.round(sales * weekend_multiplier).astype(int)

df = pd.DataFrame({
    "день": days,
    "вихідний": weekend,
    "температура": temperature,
    "продажі": sales
})

print("\nЗгенерований набір даних:")
print(df)

print("\nФорма набору:")
print(df.shape)


# ============================================================
# ЗАВДАННЯ 2. ГІСТОГРАМА
# ============================================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 2. ГІСТОГРАМА")
print("=" * 60)

# Гістограма з 6 інтервалами
fig, ax = plt.subplots(figsize=(7, 5))

ax.hist(df["продажі"], bins=6, edgecolor="black")

ax.set_xlabel("Продажі, шт./день")
ax.set_ylabel("Кількість днів")
ax.set_title("Розподіл продажів напоїв у Києві")

plt.tight_layout()
plt.show()


# Друга гістограма — 10 bins
fig, ax = plt.subplots(figsize=(7, 5))

ax.hist(df["продажі"], bins=10, edgecolor="black")

ax.set_xlabel("Продажі, шт./день")
ax.set_ylabel("Кількість днів")
ax.set_title("Розподіл продажів — 10 інтервалів")

plt.tight_layout()
plt.show()

print("""
Порівняння гістограм:
Для 30 спостережень більш змістовною є гістограма з 6 інтервалами.
Вона достатньо добре показує загальну форму розподілу і не робить
його надмірно подрібненим. Гістограма з 10 інтервалами показує
більше деталей, але для невеликого набору може виглядати занадто
фрагментованою.
""")


# ============================================================
# ЗАВДАННЯ 3. BOXPLOT
# ============================================================

print("=" * 60)
print("ЗАВДАННЯ 3. BOXPLOT")
print("=" * 60)

weekday_sales = df.loc[~df["вихідний"], "продажі"]
weekend_sales = df.loc[df["вихідний"], "продажі"]

fig, ax = plt.subplots(figsize=(7, 5))

ax.boxplot(
    [weekday_sales, weekend_sales],
    tick_labels=["Будні", "Вихідні"]
)

ax.set_ylabel("Продажі, шт./день")
ax.set_title("Продажі напоїв: будні проти вихідних")

plt.tight_layout()
plt.show()

print("Медіана будніх днів:", weekday_sales.median())
print("Медіана вихідних:", weekend_sales.median())

print("Середні продажі у будні:", round(weekday_sales.mean(), 2))
print("Середні продажі у вихідні:", round(weekend_sales.mean(), 2))

print("""
Пояснення:
Продажі у вихідні дні мають вищу медіану та середнє значення,
ніж у будні. Це узгоджується з умовою Завдання 1, оскільки
для вихідних продажі були збільшені приблизно на 15–25%.
""")


# ============================================================
# ЗАВДАННЯ 4. ДІАГРАМА РОЗСІЮВАННЯ
# ============================================================

print("=" * 60)
print("ЗАВДАННЯ 4. ДІАГРАМА РОЗСІЮВАННЯ")
print("=" * 60)

fig, ax = plt.subplots(figsize=(7, 5))

ax.scatter(
    df["температура"],
    df["продажі"]
)

ax.set_xlabel("Температура, °C")
ax.set_ylabel("Продажі, шт./день")
ax.set_title("Продажі напоїв залежно від температури")

plt.tight_layout()
plt.show()

correlation = df["температура"].corr(df["продажі"])

print("Кореляція між температурою та продажами:",
      round(correlation, 3))

print("""
Пояснення:
На діаграмі розсіювання немає чітко вираженого прямого або
зворотного зв'язку між температурою та продажами. Це очікувано,
оскільки під час генерації набору продажі змінювалися випадково
та додатково збільшувалися у вихідні, а не залежали безпосередньо
від температури.
""")


# ============================================================
# ЗАВДАННЯ 5. СПОТВОРЕНИЙ ГРАФІК
