import numpy as np
import pandas as pd

# ============================================================
# ПРАКТИЧНА РОБОТА 8
# Групування і зведені таблиці
# Варіант 1 — Київ
# ============================================================

print("=" * 70)
print("ПРАКТИЧНА РОБОТА 8")
print("Групування і зведені таблиці: groupby, agg, pivot_table, crosstab")
print("Варіант 1 — Київ")
print("=" * 70)


# ============================================================
# ВИХІДНІ ДАНІ
# ============================================================

np.random.seed(42)

city = "Київ"
base_temp = 9.5
amplitude = 14

rows = []

for year in [2021, 2022, 2023, 2024]:
    for month in range(1, 13):

        seasonal = amplitude * np.cos(
            (month - 7) / 12 * 2 * np.pi
        )

        noise = np.random.normal(0, 1.0)

        rows.append({
            "місто": city,
            "рік": year,
            "місяць": month,
            "температура": round(base_temp + seasonal + noise, 1)
        })

climate = pd.DataFrame(rows)


# ============================================================
# ЗАВДАННЯ 1. GROUPBY І AGG ЗА РОКАМИ
# ============================================================

print("\n")
print("=" * 70)
print("ЗАВДАННЯ 1. GROUPBY І AGG ЗА РОКАМИ")
print("=" * 70)

year_stats = climate.groupby("рік")["температура"].agg(
    ["mean", "min", "max"]
)

print(year_stats)

print("\nВисновок:")
print(
    "Середні температури за роками відрізняються незначно. "
    "Помітного сталого тренду на потепління або похолодання "
    "за цими чотирма роками не спостерігається. "
    "Коливання можна вважати переважно випадковими."
)


# ============================================================
# ЗАВДАННЯ 2. GROUPBY І AGG ЗА МІСЯЦЯМИ
# ============================================================

print("\n")
print("=" * 70)
print("ЗАВДАННЯ 2. GROUPBY І AGG ЗА МІСЯЦЯМИ")
print("=" * 70)

month_stats = climate.groupby("місяць")["температура"].agg(
    ["mean", "std"]
)

print(month_stats)

max_std_month = month_stats["std"].idxmax()
max_std_value = month_stats["std"].max()

print("\nМісяць із найбільшим стандартним відхиленням:")
print("Місяць:", max_std_month)
print("Стандартне відхилення:", round(max_std_value, 3))

print("\nВисновок:")
print(
    f"Найбільший розкид між роками спостерігається у {max_std_month}-му місяці. "
    "Це може бути пов'язано з нестабільністю погодних умов у перехідний "
    "сезон та різними температурними коливаннями між роками."
)


# ============================================================
# ЗАВДАННЯ 3. PIVOT_TABLE
# ============================================================

print("\n")
print("=" * 70)
print("ЗАВДАННЯ 3. PIVOT_TABLE")
print("=" * 70)

pivot = climate.pivot_table(
    index="місяць",
    columns="рік",
    values="температура",
    aggfunc="mean"
)

print(pivot)

print("\nВисновок:")
print(
    "Зведена таблиця з місяцями в рядках і роками у стовпцях "
    "зручніша для читання людиною та швидкого порівняння температур "
    "між роками. Довгий формат зручніший для groupby, фільтрації, "
    "побудови графіків та подальшого аналізу даних."
)


# ============================================================
# ЗАВДАННЯ 4. CROSSTAB
# ============================================================

print("\n")
print("=" * 70)
print("ЗАВДАННЯ 4. ПОХІДНІ КАТЕГОРІЇ І CROSSTAB")
print("=" * 70)


def get_season(month):
    if month in [12, 1, 2]:
        return "Зима"
    elif month in [3, 4, 5]:
        return "Весна"
    elif month in [6, 7, 8]:
        return "Літо"
    else:
        return "Осінь"


climate["сезон"] = climate["місяць"].apply(get_season)

climate["тепліше_за_середнє"] = (
    climate["температура"] > base_temp
)

crosstab_result = pd.crosstab(
    climate["сезон"],
    climate["тепліше_за_середнє"]
)

print(crosstab_result)

print("\nВисновок:")
print(
    "Розподіл частот відповідає сезонному характеру температури. "
    "У літні місяці більшість значень є вищими за середньорічну "
    "температуру Києва 9.5 °C. У зимовий період переважають значення "
    "нижчі за середньорічну температуру."
)


# ============================================================
# ЗАВДАННЯ 5. PIVOT()
# ============================================================

print("\n")
print("=" * 70)
print("ЗАВДАННЯ 5. PIVOT()")
print("=" * 70)

pivot_result = climate.pivot(
    index="місяць",
    columns="рік",
    values="температура"
)

print(pivot_result)

print("\nПеревірка кількості рядків для кожної комбінації місяць/рік:")

duplicates = climate.groupby(
    ["місяць", "рік"]
).size()

print(duplicates)

print("\nВисновок:")
print(
    "Метод pivot() успішно працює, тому що для кожної комбінації "
    "місяць/рік існує рівно одне значення температури. "
    "Усього маємо 4 роки × 12 місяців = 48 спостережень."
)

print(
    "\nЩоб pivot() завершився помилкою, потрібно створити дублікати "
    "комбінації місяць/рік. Наприклад, додати кілька метеостанцій "
    "для одного міста. Тоді для одного місяця та року буде кілька "
    "значень температури, і pivot() не знатиме, яке значення "
    "потрібно помістити в клітинку."
)


