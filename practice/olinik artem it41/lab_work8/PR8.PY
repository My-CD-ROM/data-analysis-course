print("""
1. Логіка split-apply-combine у groupby():

Спочатку split — дані розділяються на групи за певною ознакою,
наприклад за роком. Потім apply — до кожної групи застосовується
потрібна операція, наприклад mean, min або max. Після цього
combine — результати всіх груп об'єднуються в одну таблицю.

2. Відмінність pivot() і pivot_table():

pivot() працює лише тоді, коли кожній комбінації індексу та стовпця
відповідає одне значення. Якщо є дублікати, виникає помилка.
pivot_table() може працювати з дублікати, тому що додатково
виконує агрегування, наприклад mean, sum або max.

3. Що показує crosstab():

crosstab() будує таблицю частот для категорій. Вона показує,
скільки спостережень належить до кожної комбінації категорій.
groupby(...).size() може дати подібний результат, але crosstab()
спеціально призначений для побудови перехресних таблиць частот.

4. Чому tidy-формат зручний для groupby і pivot_table:

У довгому форматі кожен рядок є одним спостереженням, а кожен
стовпець — окремою змінною. Це дозволяє легко виконувати
groupby, фільтрацію, агрегування та побудову зведених таблиць.
Такий формат є універсальним для аналізу даних.
""")


