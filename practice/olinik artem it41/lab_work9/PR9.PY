import pandas as pd
import numpy as np

# ============================================================
# ЗАВДАННЯ 1. ПОБУДОВА НАБОРУ КЛІЄНТІВ
# ============================================================

# Варіант 1 — Київ
base_price = 850

data = {
    "вік": [19, 24, 28, 33, 41, 47, 52, 58, 63, 69],
    "дохід": [18000, 25000, 32000, 41000, 52000,
              30000, 45000, 60000, 38000, 70000],
    "кількість": [3, 4, 2, 5, 3, 6, 4, 2, 5, 3],
    "місто_доставки": [
        "Київ",
        "Львів",
        "Одеса",
        "Харків",
        "Київ",
        "Дніпро",
        "Львів",
        "Одеса",
        "Київ",
        "Харків"
    ]
}

customers = pd.DataFrame(data)

print("=" * 70)
print("ПРАКТИЧНА РОБОТА 9")
print("Варіант 1 — Київ")
print("=" * 70)

print("\nЗАВДАННЯ 1. ПОЧАТКОВИЙ НАБІР ДАНИХ")
print(customers)


# ============================================================
# ЗАВДАННЯ 2. ПОХІДНІ ЗМІННІ
# ============================================================

customers["сума_замовлення"] = base_price * customers["кількість"]

customers["частка_доходу"] = (
    customers["сума_замовлення"] / customers["дохід"]
)

print("\n" + "=" * 70)
print("ЗАВДАННЯ 2. ПОХІДНІ ЗМІННІ")
print("=" * 70)

print(customers[
    ["вік", "дохід", "кількість",
     "сума_замовлення", "частка_доходу"]
])

print("\nВисновок:")
print(
    "Частка доходу показує, яку частину місячного доходу клієнт "
    "витрачає на замовлення. Ця змінна зручніша для порівняння "
    "клієнтів із різним рівнем доходу, оскільки враховує не тільки "
    "суму замовлення, а й фінансові можливості клієнта."
)


# ============================================================
# ЗАВДАННЯ 3. ДИСКРЕТИЗАЦІЯ
# ============================================================

# 1. Поділ через cut()
customers["вікова_група_cut"] = pd.cut(
    customers["вік"],
    bins=3
)

cut_counts = customers["вікова_група_cut"].value_counts().sort_index()

print("\n" + "=" * 70)
print("ЗАВДАННЯ 3. ДИСКРЕТИЗАЦІЯ")
print("=" * 70)

print("\nГрупи через pd.cut():")
print(cut_counts)


# 2. Поділ через qcut()
customers["вікова_група_qcut"] = pd.qcut(
    customers["вік"],
    q=3
)

qcut_counts = customers["вікова_група_qcut"].value_counts().sort_index()

print("\nГрупи через pd.qcut():")
print(qcut_counts)


print("\nВисновок:")
print(
    "pd.cut() створює інтервали приблизно однакової довжини, "
    "тому кількість клієнтів у групах може сильно відрізнятися. "
    "pd.qcut() формує групи так, щоб у кожній було приблизно "
    "однакове число спостережень. Тому межі груп у cut() і qcut() "
    "відрізняються."
)


# ============================================================
# ЗАВДАННЯ 4. МАСШТАБУВАННЯ
# ============================================================

# ----------------------------
# Min-Max нормалізація
# ----------------------------

customers["вік_minmax"] = (
    (customers["вік"] - customers["вік"].min()) /
    (customers["вік"].max() - customers["вік"].min())
)

customers["дохід_minmax"] = (
    (customers["дохід"] - customers["дохід"].min()) /
    (customers["дохід"].max() - customers["дохід"].min())
)


# ----------------------------
# Z-оцінка
# ----------------------------

customers["вік_z"] = (
    (customers["вік"] - customers["вік"].mean()) /
    customers["вік"].std()
)

customers["дохід_z"] = (
    (customers["дохід"] - customers["дохід"].mean()) /
    customers["дохід"].std()
)


print("\n" + "=" * 70)
print("ЗАВДАННЯ 4. МАСШТАБУВАННЯ")
print("=" * 70)

print("\nMin-Max нормалізація:")
print(
    customers[
        ["вік", "дохід", "вік_minmax", "дохід_minmax"]
    ].round(4)
)

print("\nZ-оцінка:")
print(
    customers[
        ["вік", "дохід", "вік_z", "дохід_z"]
    ].round(4)
)

print("\nВисновок:")
print(
    "До масштабування вік і дохід мають дуже різні масштаби "
    "та одиниці вимірювання. Дохід має значно більші числові "
    "значення, тому в методах, чутливих до масштабу, він міг би "
    "мати непропорційно великий вплив. Масштабування переводить "
    "змінні до порівнюваного масштабу."
)


# ============================================================
# ЗАВДАННЯ 5. ІНДИКАТОРНЕ КОДУВАННЯ
# ============================================================

city_dummies = pd.get_dummies(
    customers["місто_доставки"],
    prefix="місто"
)

customers = pd.concat(
    [customers, city_dummies],
    axis=1
)

print("\n" + "=" * 70)
print("ЗАВДАННЯ 5. ІНДИКАТОРНЕ КОДУВАННЯ")
print("=" * 70)

print("\nУнікальні міста:")
print(customers["місто_доставки"].unique())

print("\nКількість унікальних міст:")
print(customers["місто_доставки"].nunique())

print("\nOne-Hot стовпці:")
print(city_dummies)

print("\nПеревірка:")
print(
    "Кількість нових стовпців:",
    len(city_dummies.columns)
)

print("\nВисновок:")
print(
    "Для міста доставки використовується one-hot кодування, "
    "оскільки міста є номінальною категорією і не мають природного "
    "порядку. Кодування міст числами 1, 2, 3 створило б помилкове "
    "враження, що одне місто більше або важливіше за інше."
)


# ============================================================
# ПОВНА ТАБЛИЦЯ
# ============================================================

print("\n" + "=" * 70)
print("ПОВНА ТАБЛИЦЯ ПІСЛЯ ВСІХ ПЕРЕТВОРЕНЬ")
print("=" * 70)

print(customers)


# ============================================================
# КОНТРОЛЬНІ ПИТАННЯ
# ============================================================

print("\n" + "=" * 70)
print("КОНТРОЛЬНІ ПИТАННЯ")
print("=" * 70)

print("\n1. Різниця між cut() і qcut():")
print(
    "pd.cut() ділить числові значення на інтервали однакової "
    "довжини. Через це кількість спостережень у групах може "
    "відрізнятися. pd.qcut() ділить дані на квантилі, тому "
    "кількість спостережень у групах приблизно однакова."
)

print("\n2. Чому використовується one-hot:")
print(
    "Місто є номінальною змінною без природного порядку. "
    "One-hot створює окремий індикатор для кожного міста і "
    "не створює хибного числового порядку."
)

print("\n3. Навіщо масштабувати змінні:")
print(
    "Масштабування потрібне для методів, чутливих до масштабу, "
    "наприклад дистанційних методів та регресії з регуляризацією. "
    "Воно не дозволяє змінній з великими числовими значеннями "
    "непропорційно впливати на результат."
)

print("\n4. Навіщо потрібна похідна змінна:")
print(
    "Похідна змінна може поєднати кілька показників і дати "
    "більш змістовну характеристику. Наприклад, частка доходу "
    "показує не просто суму покупки, а її відносне фінансове "
    "навантаження для конкретного клієнта."
)

print("\n" + "=" * 70)
print("ПРАКТИЧНУ РОБОТУ 9 ВИКОНАНО")
print("Варіант 1 — Київ")
print("=" * 70)