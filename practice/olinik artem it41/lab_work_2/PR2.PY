import pandas as pd

# ==========================================
# ПРАКТИЧНА РОБОТА 2
# pandas: побудова DataFrame
# Варіант 1 — Київ
# ==========================================

months = [
    "Січ", "Лют", "Бер", "Кві", "Тра", "Чер",
    "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"
]

avg_temp = [38, 36, 38, 41, 53, 74, 84, 69, 47, 36, 44, 44]

precip = [40, 35, 45, 50, 55, 65, 70, 60, 50, 45, 50, 45]

# Створення DataFrame
df = pd.DataFrame({
    "month": months,
    "avg_temp": avg_temp,
    "precip": precip
})

print("=" * 60)
print("ПРАКТИЧНА РОБОТА 2")
print("pandas: побудова DataFrame")
print("Варіант 1 — Київ")
print("=" * 60)

# ==========================================
# Перевірка DataFrame
# ==========================================

print("\nПОЧАТКОВИЙ DATAFRAME:")
print(df)

print("\nФорма DataFrame:")
print(df.shape)

print("\nТипи даних:")
print(df.dtypes)

# ==========================================
# ЗАВДАННЯ 1. ІНДЕКС
# ==========================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 1. ІНДЕКС")
print("=" * 60)

print("\n1. Індекс за замовчуванням:")
print(df.index)

# Заміна індексу на month
df_by_month = df.set_index("month")

print("\n2. DataFrame з індексом month:")
print(df_by_month)

print("\nРядок для червня через .loc:")
print(df_by_month.loc["Чер"])

# Повертаємо звичайну нумерацію
df = df_by_month.reset_index()

print("\n3. Повернення звичайної нумерації:")
print(df)

# ==========================================
# ЗАВДАННЯ 2. ВІДБІР
# ==========================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 2. ВІДБІР РЯДКІВ І СТОВПЦІВ")
print("=" * 60)

# Індекс від 1 до 12
df.index = range(1, 13)

print("\nІндекс від 1 до 12:")
print(df)

print("\n1. avg_temp для місяців 1–6 через .loc:")
print(df.loc[1:6, "avg_temp"])

print("\n2. avg_temp для позицій 0–5 через .iloc:")
print(df.iloc[0:6, 1])

print("\n3. Стовпці month і precip:")
print(df[["month", "precip"]])

# ==========================================
# ЗАВДАННЯ 3. ФІЛЬТРАЦІЯ
# ==========================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 3. ФІЛЬТРАЦІЯ ЗА УМОВОЮ")
print("=" * 60)

print("\n1. Місяці, де avg_temp > 15:")
result1 = df[df["avg_temp"] > 15]["month"]
print(result1.tolist())

print("\n2. Місяці, де avg_temp > 10 і precip > 50:")
result2 = df[
    (df["avg_temp"] > 10) &
    (df["precip"] > 50)
]["month"]
print(result2.tolist())

print("\n3. Місяці, де avg_temp < 0 або precip > 80:")
result3 = df[
    (df["avg_temp"] < 0) |
    (df["precip"] > 80)
]["month"]
print(result3.tolist())

# ==========================================
# ЗАВДАННЯ 4. ОБЧИСЛЮВАНІ СТОВПЦІ
# ==========================================

print("\n" + "=" * 60)
print("ЗАВДАННЯ 4. ОБЧИСЛЮВАНІ СТОВПЦІ")
print("=" * 60)

# 1. Температура у Фаренгейтах
df["avg_temp_f"] = df["avg_temp"] * 9 / 5 + 32

print("\n1. Стовпець avg_temp_f створено.")

# 2. Вологий місяць, якщо опади більші за середні
average_precip = df["precip"].mean()

df["is_wet"] = df["precip"] > average_precip

print("\n2. Середня кількість опадів:")
print(average_precip)

print("\nСтовпець is_wet створено.")

# 3. Визначення пори року
def get_season(month_number):
    if month_number in [12, 1, 2]:
        return "зима"
    elif month_number in [3, 4, 5]:
        return "весна"
    elif month_number in [6, 7, 8]:
        return "літо"
    else:
        return "осінь"


df["season"] = df.index.to_series().apply(get_season)

print("\n3. Стовпець season створено.")

# ==========================================
# ФІНАЛЬНА ТАБЛИЦЯ
# ==========================================

print("\n" + "=" * 60)
print("ФІНАЛЬНА ТАБЛИЦЯ")
print("=" * 60)

